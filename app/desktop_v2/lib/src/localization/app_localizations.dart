import 'package:flutter/foundation.dart';
import 'package:flutter/widgets.dart';

class SageLocalizations {
  const SageLocalizations(this.locale);

  final Locale locale;

  static const supportedLocales = <Locale>[
    Locale('zh'),
    Locale('en'),
    Locale('pt'),
    Locale('es'),
    Locale('fr'),
    Locale('de'),
    Locale('ja'),
    Locale('ko'),
    Locale('ru'),
  ];

  static const LocalizationsDelegate<SageLocalizations> delegate =
      _SageLocalizationsDelegate();

  @visibleForTesting
  static bool get translationsAreComplete {
    final expected = _translations['en']!.keys.toSet();
    return _translations.values.every(
      (translations) => setEquals(translations.keys.toSet(), expected),
    );
  }

  static SageLocalizations of(BuildContext context) =>
      Localizations.of<SageLocalizations>(context, SageLocalizations) ??
      const SageLocalizations(Locale('zh'));

  String get languageCode {
    final code = locale.languageCode.toLowerCase();
    return _translations.containsKey(code) ? code : 'en';
  }

  String text(String key, [Map<String, Object?> values = const {}]) {
    var value =
        _translations[languageCode]?[key] ?? _translations['en']?[key] ?? key;
    for (final entry in values.entries) {
      value = value.replaceAll('{${entry.key}}', '${entry.value}');
    }
    return value;
  }

  String localeName(String value) => switch (value) {
    'system' => text('common.system'),
    'zh' => '简体中文',
    'en' => 'English',
    'pt' => 'Português',
    'es' => 'Español',
    'fr' => 'Français',
    'de' => 'Deutsch',
    'ja' => '日本語',
    'ko' => '한국어',
    'ru' => 'Русский',
    _ => value,
  };

  String knownMessage(String value) => switch (value) {
    '至少需要保留一个 Agent' => text('error.keepOneAgent'),
    '运行中的会话不能归档' => text('error.runningCannotArchive'),
    '运行中的会话不能删除' => text('error.runningCannotDelete'),
    '任务状态已变化，此审批请求已失效' => text('error.approvalExpired'),
    _ => value,
  };

  String conversationTitle(String value) =>
      value == '新会话' ? text('conversation.new') : value;
}

extension SageLocalizationsContext on BuildContext {
  SageLocalizations get l10n => SageLocalizations.of(this);
}

class _SageLocalizationsDelegate
    extends LocalizationsDelegate<SageLocalizations> {
  const _SageLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => SageLocalizations.supportedLocales.any(
    (supported) => supported.languageCode == locale.languageCode,
  );

  @override
  Future<SageLocalizations> load(Locale locale) =>
      SynchronousFuture(SageLocalizations(locale));

  @override
  bool shouldReload(_SageLocalizationsDelegate old) => false;
}

